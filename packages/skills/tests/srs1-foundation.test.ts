import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import {
  contentDigest,
  loadAuthoringRegistry,
  packageRoot,
  renderRegistry,
} from "../authoring/generator.js";
import { initialSkillRegistry } from "../src/index.js";
import {
  Srs1BaselineSchema,
  Srs1DevelopmentInventorySchema,
  SrsCandidateTraceSchema,
  SrsScenarioAnnotationSchema,
  assertScenarioDefinitionKinds,
  type SrsDefinitionKind,
} from "./srs1-foundation.js";
import { skillSelectionEvaluationFixtures } from "../../test-fixtures/src/index.js";
import { phase8CandidateSelectionFixtures } from "../../test-fixtures/src/phase8-candidate-experiment.js";

const root = resolve(packageRoot, "../..");
const fixtureDir = resolve(packageRoot, "tests/fixtures/srs1");
const readRoot = (path: string) => readFile(resolve(root, path));
const json = async (name: string): Promise<unknown> =>
  JSON.parse(await readFile(resolve(fixtureDir, name), "utf8"));
const rawSha256 = (value: Uint8Array) => createHash("sha256").update(value).digest("hex");

const baseline = Srs1BaselineSchema.parse(await json("baseline.json"));
const inventory = Srs1DevelopmentInventorySchema.parse(await json("development-inventory.json"));
const { records, registry } = await loadAuthoringRegistry();
const kinds = new Map<string, SrsDefinitionKind>(
  records.map((record) => [record.definition.id, record.kind]),
);
for (const candidate of [
  "perspective_acknowledgement",
  "give_constructive_feedback",
  "confirmation",
])
  kinds.set(candidate, "ATOMIC");

describe("SRS-1 baseline and private trace foundation", () => {
  it("binds the exact production21, 14/7 type split, 210 examples and generated bytes", async () => {
    expect(registry).toEqual(initialSkillRegistry);
    expect(registry).toHaveLength(baseline.production.definitionCount);
    expect(records.filter((record) => record.kind === "ATOMIC")).toHaveLength(
      baseline.production.atomicCount,
    );
    expect(records.filter((record) => record.kind === "LANGUAGE_MODIFIER")).toHaveLength(
      baseline.production.modifierCount,
    );
    expect(
      records.reduce(
        (count, record) =>
          count + record.examples.selection.length + record.examples.application.length,
        0,
      ),
    ).toBe(baseline.production.canonicalExampleCount);
    expect(contentDigest(registry)).toBe(baseline.production.registryDigest);
    expect(rawSha256(await readRoot("packages/skills/definitions/approved-manifest.yaml"))).toBe(
      baseline.production.manifestRawSha256,
    );
    expect(rawSha256(await readRoot("packages/skills/authoring/baseline-approvals.json"))).toBe(
      baseline.production.baselineApprovalsRawSha256,
    );
    const generated = await readRoot("packages/skills/src/generated/approved-registry.ts");
    expect(rawSha256(generated)).toBe(baseline.production.generatedRegistryRawSha256);
    expect(generated.toString("utf8")).toBe(await renderRegistry());
  });

  it("binds the 153 frozen Phase 7 plans and relevant Phase 8 evidence", async () => {
    const preMigrationBytes = await readRoot(baseline.phase7.preMigrationPath);
    expect(rawSha256(preMigrationBytes)).toBe(baseline.phase7.preMigrationRawSha256);
    const preMigration = JSON.parse(preMigrationBytes.toString("utf8")) as {
      registry: unknown[];
      integration: unknown[];
      cases: unknown[];
    };
    expect(preMigration.registry).toEqual(initialSkillRegistry);
    expect(preMigration.integration).toHaveLength(baseline.phase7.frozenIntegrationPlanCount);
    expect(preMigration.cases).toHaveLength(baseline.phase7.frozenDirectPlanCount);
    expect(preMigration.integration.length + preMigration.cases.length).toBe(
      baseline.phase7.frozenPlanCount,
    );
    for (const [path, digest] of Object.entries(baseline.phase8))
      expect(rawSha256(await readRoot(path)), path).toBe(digest);
  });

  it("keeps capability and modifier expectation labels structurally separate", () => {
    for (const raw of inventory.sampleAnnotations) {
      const scenario = SrsScenarioAnnotationSchema.parse(raw);
      expect(() => assertScenarioDefinitionKinds(scenario, kinds)).not.toThrow();
    }
    const source = inventory.sampleAnnotations.find((row) => row.id === "simplified-status")!;
    const misplacedCapability = structuredClone(source);
    misplacedCapability.modifiers.required = ["status_update"];
    expect(() => assertScenarioDefinitionKinds(misplacedCapability, kinds)).toThrow(
      "Modifier label has non-modifier kind",
    );
    const misplacedModifier = structuredClone(source);
    misplacedModifier.capabilities.required = ["zh.professional_formality"];
    expect(() => assertScenarioDefinitionKinds(misplacedModifier, kinds)).toThrow(
      "Capability label has non-capability kind",
    );
  });

  it("rejects impossible, overlapping and mismatched scenario annotations", () => {
    const source = inventory.sampleAnnotations[0]!;
    expect(
      SrsScenarioAnnotationSchema.safeParse({
        ...source,
        capabilities: {
          ...source.capabilities,
          acceptable: [source.capabilities.required[0]!],
        },
      }).success,
    ).toBe(false);
    expect(
      SrsScenarioAnnotationSchema.safeParse({
        ...source,
        strictNone: true,
      }).success,
    ).toBe(false);
    expect(
      SrsScenarioAnnotationSchema.safeParse({
        ...source,
        assistanceMode: "SUGGEST_REPLY",
      }).success,
    ).toBe(false);
    expect(
      SrsScenarioAnnotationSchema.safeParse({
        ...source,
        hiddenRationale: "Do not permit private reasoning fields.",
      }).success,
    ).toBe(false);
  });

  it("uses strict closed stage traces without mixing modifier and capability lanes", () => {
    const atomic = {
      id: "status_update",
      version: 1,
      definitionType: "ATOMIC",
      catalog: "PRODUCTION",
      eligibility: { result: "NOT_RUN", reasonCodes: [] },
      retrieval: null,
      rerank: null,
      supervisor: null,
      modifierSelection: null,
      finalResolution: null,
      disappearedAt: null,
      disappearanceReasonCodes: [],
    } as const;
    expect(SrsCandidateTraceSchema.parse(atomic)).toEqual(atomic);
    expect(
      SrsCandidateTraceSchema.safeParse({ ...atomic, hiddenRationale: "because" }).success,
    ).toBe(false);
    expect(
      SrsCandidateTraceSchema.safeParse({ ...atomic, disappearedAt: "UNKNOWN_STAGE" }).success,
    ).toBe(false);
    expect(
      SrsCandidateTraceSchema.safeParse({
        ...atomic,
        definitionType: "LANGUAGE_MODIFIER",
        retrieval: { score: 1, rank: 1, matchedFeatureReasonCodes: ["INTENT_MATCH"] },
      }).success,
    ).toBe(false);
    expect(
      SrsCandidateTraceSchema.safeParse({
        ...atomic,
        modifierSelection: { selected: true, reasonCode: "DELIVERY_RELEVANT" },
      }).success,
    ).toBe(false);
    expect(
      SrsCandidateTraceSchema.safeParse({
        ...atomic,
        disappearedAt: "RETAINED",
        finalResolution: { included: false, reasonCode: "CONFLICT" },
      }).success,
    ).toBe(false);
  });

  it("inventories only exposed development evidence and leaves held-out unauthored", () => {
    expect(inventory.heldOut).toMatchObject({ status: "NOT_AUTHORED", sealed: false });
    expect(inventory.sampleAnnotations.every((row) => row.split === "DEVELOPMENT")).toBe(true);
    expect(inventory.sources).toEqual([
      expect.objectContaining({ id: "PHASE4_REGRESSION", caseCount: 21 }),
      expect.objectContaining({ id: "APPROVED_CANONICAL", caseCount: 210 }),
      expect.objectContaining({ id: "PHASE8_CANDIDATE", caseCount: 32 }),
    ]);
    const phase4Ids = new Set(skillSelectionEvaluationFixtures.map((fixture) => fixture.id));
    const phase8Ids = new Set(phase8CandidateSelectionFixtures.map((fixture) => fixture.id));
    for (const scenario of inventory.sampleAnnotations) {
      if (scenario.source.path.endsWith("index.ts"))
        expect(phase4Ids.has(scenario.source.fixtureId), scenario.id).toBe(true);
      if (scenario.source.path.endsWith("phase8-candidate-experiment.ts"))
        expect(phase8Ids.has(scenario.source.fixtureId), scenario.id).toBe(true);
    }
  });

  it("records the dirty-worktree snapshot as evidence without making it a future code freeze", () => {
    expect(baseline.workspace).toEqual({
      fileCount: 194,
      contentMapDigest: "sha256:463abb977f91ba1216fbef656f9a240a3b9051a7efd7c2af89418f7325a008a9",
    });
    expect(baseline.excludedSrs1OwnedPaths).toContain("packages/skills/tests/fixtures/srs1/");
    expect(baseline.heldOut).toEqual({ status: "NOT_AUTHORED", sealed: false });
  });

  it("keeps Phase 8 candidates outside the active production registry", () => {
    const productionIds = new Set(initialSkillRegistry.map((skill) => skill.id));
    for (const candidate of [
      "perspective_acknowledgement",
      "give_constructive_feedback",
      "confirmation",
    ])
      expect(productionIds.has(candidate)).toBe(false);
    expect(initialSkillRegistry.every((skill) => skill.status === "ACTIVE")).toBe(true);
  });
});
