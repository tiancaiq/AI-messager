import type {
  AgentAction,
  CoachingRequest,
  ConversationAnalysis,
  SkillIntentTag,
} from "@ai-message-coach/contracts";

export interface RecallRegressionCase {
  id: string;
  capability: string;
  targetIntent: SkillIntentTag;
  class: "POSITIVE" | "HARD_NEIGHBOR" | "NEGATIVE";
  variant: "FORMAL" | "NORMAL" | "ROUGH" | "FRAGMENT" | "MULTI_OPERATION" | "CONTROL";
  action: AgentAction;
  request: CoachingRequest;
}

interface Seed {
  id: string;
  capability: string;
  targetIntent: SkillIntentTag;
  class: RecallRegressionCase["class"];
  variant?: RecallRegressionCase["variant"];
  action: "REWRITE_DRAFT" | "SUGGEST_REPLY";
  other: string;
  draft?: string;
  intent?: string;
}

function scenario(seed: Seed): RecallRegressionCase {
  const analysis: ConversationAnalysis = {
    messages: [
      {
        id: "m1",
        order: 1,
        speaker: "OTHER",
        text: seed.other,
        textConfidence: 0.99,
        speakerConfidence: 0.99,
      },
    ],
    draft: { text: seed.draft ?? null, confidence: 0.99 },
    participants: [],
    visibleContact: {
      displayName: null,
      username: null,
      channelOrGroupName: null,
      platformHint: null,
      confidence: 0.2,
    },
    language: {
      primary: "en",
      secondary: null,
      script: "NOT_APPLICABLE",
      codeSwitching: false,
      supportedForLanguageSpecificSkills: true,
      confidence: 0.99,
    },
    conversation: { summary: "Synthetic exposed-development conversation.", confidence: 0.99 },
    warnings: [],
    overallConfidence: 0.99,
  };
  return {
    id: seed.id,
    capability: seed.capability,
    targetIntent: seed.targetIntent,
    class: seed.class,
    variant: seed.variant ?? (seed.class === "POSITIVE" ? "NORMAL" : "CONTROL"),
    action: seed.action,
    request: {
      analysis,
      selection: seed.intent
        ? { kind: "ACTION", id: `recall-${seed.id}`, label: "Use this goal", intent: seed.intent }
        : null,
    },
  };
}

