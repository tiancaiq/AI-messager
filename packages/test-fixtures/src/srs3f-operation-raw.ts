function request(seed: Seed): CoachingRequest {
  const [family, , other, draft, selectedGoal, earlierUser] = seed;
  const messages = [
    ...(earlierUser ? [{ speaker: "USER" as const, text: earlierUser }] : []),
    { speaker: "OTHER" as const, text: other },
  ];
  const analysis: ConversationAnalysis = {
    messages: messages.map((message, index) => ({
      id: `m${index + 1}`,
      order: index + 1,
      speaker: message.speaker,
      text: message.text,
      textConfidence: 0.99,
      speakerConfidence: 0.99,
    })),
    draft: { text: draft, confidence: 0.99 },
    participants: [],
    visibleContact: {
      displayName: null,
      username: null,
      channelOrGroupName: null,
      platformHint: null,
      confidence: 0.2,
    },
    language: {
      primary: "en",
      secondary: null,
      script: "NOT_APPLICABLE",
      codeSwitching: false,
      supportedForLanguageSpecificSkills: true,
      confidence: 0.99,
    },
    conversation: { summary: `Synthetic ${family} exchange.`, confidence: 0.99 },
    warnings: [],
    overallConfidence: 0.99,
  };
  return {
    analysis,
    selection: selectedGoal
      ? { kind: "ACTION", id: family, label: "Use stated goal", intent: selectedGoal }
      : null,
  };
}

export const srs3fOperationRaw: readonly OperationRawCase[] = seeds.map((seed, index) => ({
  id: `O${String(index + 1).padStart(2, "0")}`,
  revision: "R1",
  split: index % 2 === 0 ? "CALIBRATION" : "AUDIT",
  scenarioFamily: seed[0],
  fixedAction: seed[1],
  request: request(seed),
}));
