import type {
  AgentAction,
  CoachingRequest,
  ConversationAnalysis,
} from "@ai-message-coach/contracts";

export type ChallengeSetting = "WORK" | "PERSONAL" | "SERVICE";
export type ChallengeLanguage =
  "ENGLISH" | "SIMPLIFIED_CHINESE" | "TRADITIONAL_CHINESE" | "CODE_SWITCHING";

export interface ChallengeRawScenario {
  id: `C${number}` | `M${number}`;
  revision: "R1";
  scenarioFamily: string;
  split: "EXPOSED_DEVELOPMENT";
  request: CoachingRequest;
  fixedAction: AgentAction;
  catalogScope: "PRODUCTION";
  setting: ChallengeSetting;
  languageGroup: ChallengeLanguage;
}

type Speaker = "OTHER" | "USER";
interface Seed {
  id: ChallengeRawScenario["id"];
  family: string;
  setting: ChallengeSetting;
  action: AgentAction;
  messages: Array<[Speaker, string]>;
  draft: string | null;
  goal?: string;
  language?: ChallengeLanguage;
}

function raw(seed: Seed): ChallengeRawScenario {
  const group = seed.language ?? "ENGLISH";
  const chinese = group !== "ENGLISH";
  const analysis: ConversationAnalysis = {
    messages: seed.messages.map(([speaker, text], index) => ({
      id: `m${index + 1}`,
      order: index + 1,
      speaker,
      text,
      textConfidence: 0.99,
      speakerConfidence: 0.99,
    })),
    draft: { text: seed.draft, confidence: 0.99 },
    participants: [],
    visibleContact: {
      displayName: null,
      username: null,
      channelOrGroupName: null,
      platformHint: null,
      confidence: 0.2,
    },
    language: {
      primary: chinese ? "zh" : "en",
      secondary: group === "CODE_SWITCHING" ? "en" : null,
      script:
        group === "TRADITIONAL_CHINESE" ? "TRADITIONAL" : chinese ? "SIMPLIFIED" : "NOT_APPLICABLE",
      codeSwitching: group === "CODE_SWITCHING",
      supportedForLanguageSpecificSkills: true,
      confidence: 0.99,
    },
    conversation: { summary: "Synthetic challenge conversation.", confidence: 0.99 },
    warnings: [],
    overallConfidence: 0.99,
  };
  return {
    id: seed.id,
    revision: "R1",
    scenarioFamily: seed.family,
    split: "EXPOSED_DEVELOPMENT",
    request: {
      analysis,
      selection: seed.goal
        ? {
            kind: "ACTION",
            id: `challenge-${seed.id.toLowerCase()}`,
            label: "Use this goal",
            intent: seed.goal,
          }
        : null,
    },
    fixedAction: seed.action,
    catalogScope: "PRODUCTION",
    setting: seed.setting,
    languageGroup: group,
  };
}

