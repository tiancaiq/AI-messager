function makeRaw(seed: Seed): Srs4AuditRaw {
  const [id, scenarioFamily, setting, role, fixedAction, messages, draft, goal] = seed;
  const analysis: ConversationAnalysis = {
    messages: messages.map((line, index) => ({
      id: `m${index + 1}`,
      order: index + 1,
      speaker: line.startsWith("U:") ? "USER" : line.startsWith("O:") ? "OTHER" : "UNKNOWN",
      text: line.slice(2),
      speakerConfidence: 0.99,
      textConfidence: 0.99,
    })),
    draft: { text: draft, confidence: 0.99 },
    participants: [],
    visibleContact: {
      displayName: null,
      username: null,
      channelOrGroupName: null,
      platformHint: null,
      confidence: 0.2,
    },
    language: {
      primary: "en",
      secondary: null,
      script: "NOT_APPLICABLE",
      codeSwitching: false,
      supportedForLanguageSpecificSkills: true,
      confidence: 0.99,
    },
    conversation: { summary: "Synthetic SRS-4 audit case.", confidence: 0.99 },
    warnings: [],
    overallConfidence: 0.99,
  };
  return {
    id,
    revision: "R1",
    split: "EXPOSED_AUDIT_UNSCORED",
    scenarioFamily,
    setting,
    role,
    fixedAction,
    request: {
      analysis,
      selection: goal
        ? { kind: "ACTION", id: `audit-${id}`, label: "Selected goal", intent: goal }
        : null,
    },
  };
}

// Independent of B rankings and of any Supervisor output. Never imported into a model prompt.
export const srs4AuditRaw: readonly Srs4AuditRaw[] = seeds.map(makeRaw);
